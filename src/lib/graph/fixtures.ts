export interface FixtureExpect {
	/** Bubbles stage 1 pops. */
	sites: number;
	/** Total non-reference interior nodes stage 1 removes. */
	nodesRemoved: number;
	/** Of those, single-base ones (SNPs). */
	snpCount: number;
	/** Total non-reference interior bases stage 1 removes. */
	basesRemoved: number;
	/** Segment ids that must be gone after Simplify. */
	removedNodes?: string[];
	/** Segment ids that must survive Simplify. */
	keptNodes?: string[];
	/** Segment count after Simplify and unchop, if pinned. */
	segmentsAfterSimplify?: number;
}

export interface Fixture {
	id: string;
	label: string;
	description: string;
	kind: 'synthetic' | 'real';
	referenceSample: string;
	gfaText: string;
	expect?: FixtureExpect;
}

